#!/usr/bin/env node
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');

const sources = [
  resolve(root, 'src-tauri/src/error.rs'),
  resolve(root, 'src-tauri/src/search_engine/mod.rs'),
];

const kindRegex = /=>\s*"([a-z][a-z0-9_]*)"/g;
const harvested = new Set();

const tsOnlyKinds = [
  'uncaught_exception',
  'unhandled_rejection',
  'render_error',
  'invoke_unknown',
  'extension_proxy_error',
  'extension_crash',
  'iframe_uncaught',
  'iframe_unhandled_rejection',
  'rpc_timeout',
  'panic',
  'manual',
  'action_failed',
  'e2ee_enrollment_failed',
  'e2ee_passphrase_required',
  'e2ee_key_derivation_failed',
  'e2ee_decrypt_failed',
  'e2ee_key_version_mismatch',
];

for (const path of sources) {
  const text = readFileSync(path, 'utf8');
  const fnKindMatches = text.matchAll(/fn kind\(&self\)[^{]*\{([\s\S]*?)\n\s*\}/g);
  for (const fnKind of fnKindMatches) {
    for (const m of fnKind[1].matchAll(kindRegex)) {
      harvested.add(m[1]);
    }
  }
}

for (const k of tsOnlyKinds) harvested.add(k);

const sorted = [...harvested].sort();
const out = `// AUTO-GENERATED by scripts/generate-diagnostic-kinds.mjs — do not edit.
// Run \`pnpm gen:diagnostic-kinds\` after changing AppError or SearchError.
//
// Generated: ${new Date().toISOString()}

export const KNOWN_DIAGNOSTIC_KINDS = [
${sorted.map((k) => `  ${JSON.stringify(k)},`).join('\n')}
] as const;

export const DIAGNOSTIC_KINDS = KNOWN_DIAGNOSTIC_KINDS;

export type DiagnosticKind = (typeof KNOWN_DIAGNOSTIC_KINDS)[number];
`;

const dest = resolve(root, 'src/services/diagnostics/kinds.ts');
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(dest, out, 'utf8');
console.log(`wrote ${dest} with ${sorted.length} kinds`);
